__attribute__((weak)) void soma_kbd_demo(void ) {
    kputs("[ovel] keyboard demo: type, use <- -> to move cursor, Enter to finish\n");
    kputs("       (times out after ~6s in headless mode)\n");
    char line[40];
    int i = 0;
    int pos = 0;
    unsigned last = ktick();
    while ((i < 39)) {
        int c = kgetchar();
        if ((c >= 0)) {
            last = ktick();
            if ((c == '\n')) {
                line[i] = 0;
                kputs("\n");
                break;
            }
            if ((c == 128)) {
                if ((pos > 0)) {
                    (pos)--;
                    kcur_move(-1);
                }
                continue;
            }
            if ((c == 129)) {
                if ((pos < i)) {
                    kcur_move(1);
                    (pos)++;
                }
                continue;
            }
            if (((c == 130) || (c == 131))) {
                continue;
            }
            if ((c == '\x08')) {
                if ((pos > 0)) {
                    int j;
                    for (j = (pos - 1); (j < (i - 1)); (j)++) {
                        line[j] = line[(j + 1)];
                    }
                    (i)--;
                    (pos)--;
                    kcur_move(-1);
                    for (j = pos; (j < i); (j)++) {
                        kputc(line[j]);
                    }
                    kputc(' ');
                    for (j = i; (j >= pos); (j)--) {
                        kcur_move(-1);
                    }
                }
                continue;
            }
            {
                int j;
                for (j = i; (j > pos); (j)--) {
                    line[j] = line[(j - 1)];
                }
                line[pos] = (char)c;
                (i)++;
                (pos)++;
                for (j = (pos - 1); (j < i); (j)++) {
                    kputc(line[j]);
                }
                for (j = i; (j > pos); (j)--) {
                    kcur_move(-1);
                }
            }
        }
        else {
            if (((ktick() - last) > 600)) {
                kputs("\n       [timeout] no keyboard input\n");
                line[i] = 0;
                return;
            }
        }
    }
    line[i] = 0;
    kputs("       you typed: '");
    kputs(line);
    kputs("'\n");
}

